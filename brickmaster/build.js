// src/shell.html 에 src/js/*.js 를 파일명 순서대로 이어 붙여 index.html 한 파일로 만든다.
// index.html 은 아티팩트로 그대로 게시하는 결과물이라 직접 고치지 않는다.
// brickmaster-app/game-html.js 도 같은 결과물을 Expo 앱용으로 감싼 것이다.
const fs = require('fs');
const path = require('path');
const src = path.join(__dirname, 'src');
const js = fs.readdirSync(path.join(src, 'js'))
  .filter(f => f.endsWith('.js'))
  .sort()
  .map(f => `// ---- ${f} ----\n` + fs.readFileSync(path.join(src, 'js', f), 'utf8'))
  .join('\n');
const out = fs.readFileSync(path.join(src, 'shell.html'), 'utf8').replace('/*__JS__*/', () => js);
fs.writeFileSync(path.join(__dirname, 'index.html'), out);
// The Expo app (../brickmaster-app) loads the same game as a full HTML document in a WebView.
const appDir = path.join(__dirname, '..', 'brickmaster-app');
if (fs.existsSync(appDir)) {
  const doc = '<!doctype html><html lang="ko"><head><meta charset="utf-8">'
    + '<meta name="viewport" content="width=device-width,initial-scale=1,maximum-scale=1,user-scalable=no,viewport-fit=cover">'
    + '<style>html,body{margin:0}[hidden]{display:none!important}</style></head><body>' + out + '</body></html>';
  fs.writeFileSync(path.join(appDir, 'game-html.js'),
    '// Generated by brickmaster/build.js from brickmaster/src. Do not edit.\nexport default ' + JSON.stringify(doc) + ';\n');
  console.log('brickmaster-app/game-html.js', (doc.length / 1024).toFixed(1) + ' KB');
}
console.log('brickmaster/index.html', (out.length / 1024).toFixed(1) + ' KB');
